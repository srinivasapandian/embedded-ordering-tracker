const STAGE_EVENTS: Array<[ClientStage, string, string]> = [
  ['onboarded', 'Website added', 'Site registered in the tracker'],
  ['onboarded', 'Client onboarded', 'Kickoff call completed and access shared'],
  ['requirements', 'Requirements gathered', 'Menu, branding and integrations confirmed'],
  ['ordering', 'Ordering configured', 'Embedded ordering set up and connected'],
  ['migration', 'Migration started', 'Next.js migration branch created'],
  ['qa', 'QA started', 'Regression checklist opened'],
  ['completed', 'Marked completed', 'All onboarding work signed off'],
]

function buildActivity(raw: RawClient, createdAt: string, updatedAt: string): ActivityEvent[] {
  const stageIdx = CLIENT_STAGES_ORDERED.indexOf(raw.stage)
  const events = STAGE_EVENTS.filter(([s]) => CLIENT_STAGES_ORDERED.indexOf(s) <= stageIdx)
  const start = new Date(createdAt).getTime()
  const end = new Date(updatedAt).getTime()
  const step = events.length > 1 ? (end - start) / (events.length - 1) : 0
  return events.map(([, title, description], i) => ({
    id: `act-${raw.name.replace(/\W+/g, '').toLowerCase()}-${i}`,
    date: new Date(start + step * i).toISOString(),
    title,
    description,
  }))
}

export const seedClients: Client[] = rawClients.map((raw, i) => {
  const id = `c${pad2(i + 1)}`
  const createdAt = daysAgoIso(150 - i * 3, 9, (i * 7) % 60)
  const updatedAt = daysAgoIso(i % 11, 11 + (i % 6), (i * 13) % 60)
  const domain = raw.sites[0]![1]
  const firstName = raw.contact.split(' ')[0]!.toLowerCase().replace(/\W/g, '')
  return {
    id,
    name: raw.name,
    contactName: raw.contact,
    email: `${firstName}@${domain.replace(/^.*?([\w-]+\.\w+)$/, '$1')}`,
    phone: `+1 (${214 + (i % 7)}) 55${i % 10}-${String(1200 + i * 37).slice(0, 4)}`,
    location: raw.location,
    status: raw.status,
    stage: raw.stage,
    priority: raw.priority,
    assignedToId: raw.assigned,
    notes: raw.notes ?? '',
    activity: buildActivity(raw, createdAt, updatedAt),
    createdAt,
    updatedAt,
  }
})

